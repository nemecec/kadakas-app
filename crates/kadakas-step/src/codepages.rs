/// The page that `\P<letter>\` selects: `None` for a letter outside A to I.
pub fn page_of(letter: u8) -> Option<usize> {
    match letter {
        b'A'..=b'I' => Some((letter - b'A') as usize),
        _ => None,
    }
}

/// The character of the byte `code` in the page (0 is part 1). Codes below 0x80 are ASCII, the
/// controls 0x80 to 0x9F are the C1 controls of every part.
pub fn char_of(page: usize, code: u8) -> char {
    match code {
        0..=0x9F => code as char,
        c => PAGES[page.min(8)][(c - 0xA0) as usize],
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pages_map_known_codes() {
        assert_eq!(char_of(0, 0xE4), '\u{E4}');
        assert_eq!(char_of(1, 0xB1), '\u{105}');
        assert_eq!(char_of(4, 0xB0), '\u{410}');
        assert_eq!(char_of(6, 0xE1), '\u{3B1}');
        assert_eq!(char_of(8, 0xD0), '\u{11E}');
        assert_eq!(char_of(0, 0x41), 'A');
        assert_eq!(page_of(b'B'), Some(1));
        assert_eq!(page_of(b'Z'), None);
    }
}
