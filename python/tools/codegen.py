"""Generates ``kadakas/_api.py`` from the ``describe`` answer of a Kadakas session.

The generated file has one method per JSON-RPC method, with the text of ``describe`` as its
docstring, and one ``TypedDict`` per method with its parameters (names, types, required ones,
allowed values). The ``TypedDict`` classes are made from the JSON Schemas that
``describe {schemas: true}`` returns: the same parameter structs (Rust, ``kadakas-api/src/params``)
that the program uses to parse a call and to refuse an unknown parameter. The methods take ``**params``. A type checker that has ``typing_extensions``
checks the names and the types of a call, and the program still checks them at run time. Run the
script again after the API changes::

    python python/tools/codegen.py            # write the file
    python python/tools/codegen.py --check    # fail if the file is out of date

Use ``--binary PATH`` for a ``kadakas`` program that is not on PATH (or set ``KADAKAS_BIN``).
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / "kadakas" / "_api.py"

HEADER = '''\
"""The whole JSON-RPC API, one method per call. Generated by ``python/tools/codegen.py``.

Do not edit this file. Run the script again after the API changes. The high-level classes in
``kadakas.document`` use these methods, and a test checks that this file matches ``describe``.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Callable

if TYPE_CHECKING:  # the parameter types are for type checkers; nothing of this runs
    from typing import Literal, TypedDict

    from typing_extensions import Required, Unpack

Id = str
"""The ID of an object, layer, class or resource: a UUID text such as
``0190f1c2-7a3b-7c1d-8e2f-123456789abc``. Parameters and results that the text of a method calls
an ID have this type. A parameter that takes a layer or a class also takes its unique name."""
'''

HEADER_CLASS = '''

class Api:
    """Every API method as a Python method. Give the parameters as keyword arguments."""

    def __init__(self, call: Callable[[str, dict[str, Any] | None], Any]) -> None:
        self._call = call
'''


def method_name(rpc: str) -> str:
    return rpc.replace(".", "_")


def class_name(rpc: str) -> str:
    """The name of the ``TypedDict`` of the parameters of a method."""
    return "".join(part.capitalize() for part in rpc.replace(".", "_").split("_")) + "Params"


def py_type(schema: dict) -> str:
    """The Python type (as text) of the JSON Schema of a parameter."""
    if not isinstance(schema, dict):
        return "Any"
    if "const" in schema:
        return "Literal[" + repr(schema["const"]) + "]"
    if "enum" in schema:
        values = [v for v in schema["enum"] if v is not None]
        text = "Literal[" + ", ".join(repr(v) for v in values) + "]"
        return text + " | None" if len(values) < len(schema["enum"]) else text
    if "anyOf" in schema or "oneOf" in schema:
        options: list[str] = []
        for option in schema.get("anyOf") or schema["oneOf"]:
            t = py_type(option)
            if t not in options:
                options.append(t)
        return " | ".join(options)
    t = schema.get("type")
    if isinstance(t, list):
        # ["string", "null"]: an optional parameter that may be null.
        return " | ".join(dict.fromkeys(py_type({**schema, "type": one}) for one in t))
    if t == "string":
        return "str"
    if t == "number":
        return "float"
    if t == "integer":
        return "int"
    if t == "boolean":
        return "bool"
    if t == "null":
        return "None"
    if t == "array":
        return "list[" + py_type(schema.get("items", {})) + "]"
    if t == "object":
        extra = schema.get("additionalProperties")
        return f"dict[str, {py_type(extra)}]" if isinstance(extra, dict) else "dict[str, Any]"
    return "Any"


def merged_properties(schema: dict) -> dict[str, list[str]]:
    """The properties of a schema as Python types. A union of parameter sets (a tagged union) has
    the properties of all its branches; a name in several branches gets all their types."""
    found: dict[str, list[str]] = {}
    for key, prop in schema.get("properties", {}).items():
        found.setdefault(key, []).append(py_type(prop))
    for branch in schema.get("oneOf", []) + schema.get("anyOf", []):
        for key, types in merged_properties(branch).items():
            found.setdefault(key, []).extend(types)
    return found


def params_class(rpc: str, schema: dict) -> str:
    """The ``TypedDict`` of the parameters of a method, in the form that allows any key text."""
    required = set(schema.get("required", []))
    branches = schema.get("oneOf", []) + schema.get("anyOf", [])
    if branches:
        # A name that every branch of a union of parameter sets requires is required.
        required |= set.intersection(*(set(b.get("required", [])) for b in branches))
    name = class_name(rpc)
    fields = []
    for key, types in merged_properties(schema).items():
        t = " | ".join(dict.fromkeys(types))
        fields.append(f"    {key!r}: {'Required[' + t + ']' if key in required else t},")
    body = "\n" + "\n".join(fields) + "\n" if fields else ""
    return f'{name} = TypedDict("{name}", {{{body}}}, total=False)'


def describe_from_binary(binary: str | None) -> dict:
    program = binary or os.environ.get("KADAKAS_BIN") or shutil.which("kadakas")
    if not program:
        sys.exit("cannot find kadakas: pass --binary, set KADAKAS_BIN or put it on PATH")
    request = {"jsonrpc": "2.0", "id": 1, "method": "describe", "params": {"schemas": True}}
    out = subprocess.run(
        [program, "serve"],
        input=json.dumps(request) + "\n",
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    ).stdout
    return json.loads(out)["result"]


def render(describe: dict) -> str:
    """The text of ``_api.py`` for a ``describe`` answer (with ``method_schemas``)."""
    methods = describe["methods"]
    schemas = describe["method_schemas"]
    seen: dict[str, str] = {}
    lines = [HEADER]
    classes = [params_class(m["name"], schemas[m["name"]]) for m in methods]
    lines.append("if TYPE_CHECKING:\n    # The parameters of each method, from describe {schemas: true}.\n")
    lines.append("\n".join("    " + c.replace("\n", "\n    ") + "\n" for c in classes))
    lines.append(HEADER_CLASS)
    for m in methods:
        name = method_name(m["name"])
        if name in seen:
            raise SystemExit(f"{m['name']} and {seen[name]} give the same Python name {name}")
        seen[name] = m["name"]
        doc = m["doc"].replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        lines.append(
            f'    def {name}(self, **params: "Unpack[{class_name(m["name"])}]") -> Any:\n'
            f'        """{doc}\n\n'
            f'        JSON-RPC method ``{m["name"]}``."""\n'
            f'        return self._call("{m["name"]}", params or None)\n'
        )
    names = ",\n".join(f'    "{m["name"]}"' for m in methods)
    ops = sorted({e["op"] for e in describe["command_examples"]})
    lines.append(f"\nMETHOD_NAMES: tuple[str, ...] = (\n{names},\n)\n")
    lines.append(f"COMMAND_OPS_EXAMPLED: tuple[str, ...] = {tuple(ops)!r}\n")
    lines.append(f"UNITS: str = {describe['units']!r}\n")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--binary", help="the kadakas program")
    ap.add_argument("--check", action="store_true", help="only check that the file is up to date")
    ap.add_argument("--describe", help="read the describe answer (JSON, with method_schemas) from this file")
    args = ap.parse_args()
    if args.describe:
        describe = json.loads(Path(args.describe).read_text(encoding="utf-8"))
    else:
        describe = describe_from_binary(args.binary)
    text = render(describe)
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            sys.exit(f"{TARGET} is out of date. Run python/tools/codegen.py")
        print("up to date")
        return
    # LF on every system, so the file in a checkout is the same everywhere.
    with TARGET.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {TARGET} ({len(describe['methods'])} methods)")


if __name__ == "__main__":
    main()
