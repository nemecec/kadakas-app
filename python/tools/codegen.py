"""Generates ``kadakas/_api.py`` from the ``describe`` answer of a Kadakas session.

The generated file has one method per JSON-RPC method, with the text of ``describe`` as its
docstring. Run it again after the API changes::

    python python/tools/codegen.py            # write the file
    python python/tools/codegen.py --check    # fail if the file is out of date

Use ``--binary PATH`` for a ``kadakas`` program that is not on PATH (or set ``KADAKAS_BIN``).
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / "kadakas" / "_api.py"

HEADER = '''\
"""The whole JSON-RPC API, one method per call. Generated by ``python/tools/codegen.py``.

Do not edit this file. Run the script again after the API changes. The high-level classes in
``kadakas.document`` use these methods, and a test checks that this file matches ``describe``.
"""

from __future__ import annotations

from typing import Any, Callable

Id = str
"""The ID of an object, layer, class or resource: a UUID text such as
``0190f1c2-7a3b-7c1d-8e2f-123456789abc``. Parameters and results that the text of a method calls
an ID have this type."""


class Api:
    """Every API method as a Python method. Give the parameters as keyword arguments."""

    def __init__(self, call: Callable[[str, dict[str, Any] | None], Any]) -> None:
        self._call = call
'''


def method_name(rpc: str) -> str:
    return rpc.replace(".", "_")


def describe_from_binary(binary: str | None) -> dict:
    program = binary or os.environ.get("KADAKAS_BIN") or shutil.which("kadakas")
    if not program:
        sys.exit("cannot find kadakas: pass --binary, set KADAKAS_BIN or put it on PATH")
    out = subprocess.run(
        [program, "serve"],
        input=json.dumps({"jsonrpc": "2.0", "id": 1, "method": "describe"}) + "\n",
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return json.loads(out)["result"]


def render(describe: dict) -> str:
    """The text of ``_api.py`` for a ``describe`` answer."""
    methods = describe["methods"]
    seen: dict[str, str] = {}
    lines = [HEADER]
    for m in methods:
        name = method_name(m["name"])
        if name in seen:
            raise SystemExit(f"{m['name']} and {seen[name]} give the same Python name {name}")
        seen[name] = m["name"]
        doc = m["doc"].replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        lines.append(
            f"    def {name}(self, **params: Any) -> Any:\n"
            f'        """{doc}\n\n'
            f'        JSON-RPC method ``{m["name"]}``."""\n'
            f'        return self._call("{m["name"]}", params or None)\n'
        )
    names = ",\n".join(f'    "{m["name"]}"' for m in methods)
    ops = sorted({e["op"] for e in describe["command_examples"]})
    lines.append(f"\nMETHOD_NAMES: tuple[str, ...] = (\n{names},\n)\n")
    lines.append(f"COMMAND_OPS_EXAMPLED: tuple[str, ...] = {tuple(ops)!r}\n")
    lines.append(f"UNITS: str = {describe['units']!r}\n")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--binary", help="the kadakas program")
    ap.add_argument("--check", action="store_true", help="only check that the file is up to date")
    ap.add_argument("--describe", help="read the describe answer (JSON) from this file")
    args = ap.parse_args()
    if args.describe:
        describe = json.loads(Path(args.describe).read_text(encoding="utf-8"))
    else:
        describe = describe_from_binary(args.binary)
    text = render(describe)
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            sys.exit(f"{TARGET} is out of date. Run python/tools/codegen.py")
        print("up to date")
        return
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} ({len(describe['methods'])} methods)")


if __name__ == "__main__":
    main()
